"""Generated plan.md blocks of an ask: its skills and tools, and a sign-off checklist of options, milestones and tasks the user ticks."""

import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import ask_packs

Json = dict[str, Any]
SKILLS_BLOCK = re.compile(r"<!-- hve:skills -->.*?<!-- /hve:skills -->\n?", re.S)
CHECKLIST_BLOCK = re.compile(r"<!-- hve:checklist -->.*?<!-- /hve:checklist -->\n?", re.S)
TICK = re.compile(r"^- \[([ xX])\] ((?:opt|stage|task|gate):[\w.-]+)", re.M)
OPTIONS = {
    "opt:evaluation": "Output evaluation when the work is done: rubrics, validation and a council of three models",
}
VALUES = {"opt": ("on", "off", "done"), "stage": ("accepted", "changes", "skipped"), "task": ("accepted", "changes", "skipped"),
          "gate": ("on", "off")}
TICKED = {"on", "done", "accepted", "skipped"}
SHOWN = {"skipped": "continued without review", "changes": "needs changes"}
DECK = re.compile(r"\b(presentations?|decks?|slides?|slideware|pptx|powerpoint)\b", re.I)


def plugin_skills(stages: list[Json], request: str) -> dict[str, list[str]]:
    """Return the plugin skills the ask must follow, each with the stages that name it; any deck request gets presentation-deck and frontend-slides."""
    found: dict[str, list[str]] = {}
    for stage in (s for s in stages if s["status"] != "skipped"):
        for name in stage["plugin_skills"]:
            found.setdefault(name, []).append(stage["name"])
    if DECK.search(request):
        found.setdefault("presentation-deck", ["every stage"])
        found.setdefault("frontend-slides", ["every stage"])
    return found


def now() -> str:
    """Return the current UTC time in ISO 8601 seconds."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def skills_block(data: Json) -> str:
    """Return the generated plan.md block listing the ask's skills (with a set under the guideline) and MCP tool load."""
    s = data["skills"]
    why = {r["name"]: r["reason"] + (f", score {r['score']}/10: {r['why']}" if "score" in r else "") for r in s["selected"]}
    rows = "\n".join(f"| {r['name']} | {r['status']} | {why[r['name']]} | {r['skill_tokens']:,} | {'yes' if r['name'] in s['suggested'] else 'no'} |"
                     for r in s["selected"]) or "| none | | | | |"
    warning = (f"\n**Over the loadout guideline** ({s['budget']['max_skills']} skills, {s['budget']['max_tokens']:,} tokens): these skills "
               f"add their tokens to every turn of this ask. Suggested set: {len(s['suggested'])} skills, {s['suggested_tokens']:,} tokens "
               "(`lifecycle.py skills suggested`); keep all with `lifecycle.py skills all`.\n" if s["over_budget"] else "")
    choice = (f"\nChoice: {s['choice']['choice']} ({s['choice']['tokens']:,} tokens, {s['choice']['over_guideline_tokens']:,} over the "
              "guideline; the report records how much of it was cached).\n" if s.get("choice") else "")
    load = data["environment"]["tool_load"]
    servers = "\n".join(f"- {h}: {', '.join(v['servers'])} (about {v['estimated_tokens']:,} tokens of tool definitions)"
                        for h, v in load["harnesses"].items()) or "- none configured"
    tool_warning = "".join(f"\n**Tool load over {load['warn_tokens']:,} tokens**: {w}. Disable MCP servers this ask does not need.\n"
                           for w in load["warnings"])
    plugin = "".join(f"- {name} ({', '.join(stages)})\n" for name, stages in s["plugin"].items()) or "- none\n"
    return (f"<!-- hve:skills -->\n## Skills and tools (generated by lifecycle.py)\n\n{len(s['selected'])} skills, {s['tokens']:,} tokens.\n"
            f"{warning}{choice}\n| Skill | Status | Why | Tokens | Suggested |\n|---|---|---|---|---|\n{rows}\n\n"
            f"Plugin skills to follow (always on, outside the skill budget):\n{plugin}\n{ask_packs.plan_lines(data)}\n"
            f"MCP servers per harness:\n{servers}\n{tool_warning}<!-- /hve:skills -->\n")


def items(data: Json) -> list[str]:
    """Return the ids of the ask's checklist items: options, review gates (asks with gates=ticked), milestones (stages not skipped) and tasks."""
    open_stages = [s["name"] for s in data["stages"] if s["status"] != "skipped"]
    gates = [f"gate:{s}" for s in open_stages] if data.get("gates") == "ticked" else []
    return [*OPTIONS, *gates, *(f"stage:{s}" for s in open_stages), *(f"task:{t['name']}" for t in data["tasks"])]


def ticked(data: Json, item: str) -> bool:
    """Return whether the item is signed off (an option on or done, a milestone or task accepted or continued without review)."""
    return item in data["checklist"] and data["checklist"][item]["value"] in TICKED


def record(data: Json, item: str, value: str, note: str, by: str) -> Json:
    """Record a sign-off value for a checklist item and log it as a decision."""
    if item not in items(data):
        raise ValueError(f"{item!r} is not on the ask's checklist; items: {items(data)}")
    allowed = VALUES[item.split(":", 1)[0]]
    if value not in allowed:
        raise ValueError(f"{item} takes {list(allowed)}, not {value!r}")
    entry = {"value": value, "note": note, "by": by, "ts": now()}
    data["checklist"][item] = entry
    data["decisions"].append({"ts": entry["ts"], "stage": item, "choice": value, "why": note or f"ticked in {by}"})
    return {"item": item} | entry


def unfinished(data: Json) -> list[str]:
    """Return why the ask is not finished: milestones not done, or an output evaluation the user asked for that has not run."""
    open_stages = [s["name"] for s in data["stages"] if s["status"] not in ("done", "skipped")]
    reasons = [f"milestones not done: {', '.join(open_stages)}"] if open_stages else []
    if data["checklist"].get("opt:evaluation", {}).get("value") == "on":
        reasons.append("the output evaluation you asked for has not run")
    return reasons


def state(data: Json, item: str) -> str:
    """Return the recorded sign-off of an item as a trailing note, or nothing when it is open."""
    if item not in data["checklist"]:
        return ""
    entry = data["checklist"][item]
    return f" — **{SHOWN.get(entry['value'], entry['value'])}** ({entry['by']}{': ' + entry['note'] if entry['note'] else ''})"


def checklist_block(data: Json) -> str:
    """Return the generated plan.md sign-off checklist: options to opt into, then each milestone and task with persona and evidence."""
    box = {True: "x", False: " "}
    persona = {s["name"]: data["agent"] if s["agent"] == "self" else s["agent"] for s in data["stages"]}
    lines = ["<!-- hve:checklist -->", "## Sign-off checklist (generated by lifecycle.py)", "",
             "Tick an item here, or answer the agent's form; `lifecycle.py tick <item> <value>` records it. Open items stay unticked.", "",
             "**Options**"]
    lines += [f"- [{box[ticked(data, i)]}] {i} — {label}{state(data, i)}" for i, label in OPTIONS.items()]
    if data.get("gates") == "ticked":
        lines += ["", "**Pause for my review after** (unticked milestones run on without stopping)"]
        lines += [f"- [{box[ticked(data, 'gate:' + s['name'])]}] gate:{s['name']}{state(data, 'gate:' + s['name'])}"
                  for s in data["stages"] if s["status"] != "skipped"]
    lines += ["", "**Milestones**"]
    for s in data["stages"]:
        if s["status"] == "skipped":
            lines.append(f"- stage:{s['name']} — skipped: {s['note']}")
            continue
        detail = "; ".join(part for part in (f"persona {persona[s['name']]}", f"skills {', '.join(s['skills'])}" if s["skills"] else "",
                                             f"templates {', '.join(s['templates'])}" if s["templates"] else "", f"gate: {s['exit']}",
                                             f"status {s['status']}") if part)
        lines.append(f"- [{box[ticked(data, 'stage:' + s['name'])]}] stage:{s['name']} — {s['goal']} ({detail}){state(data, 'stage:' + s['name'])}")
    if data["tasks"]:
        lines += ["", "**Tasks** (evidence from each check)"]
        lines += [f"- [{box[ticked(data, 'task:' + t['name'])]}] task:{t['name']} — {t['milestone']}, {t['persona']}; check "
                  f"{'passes' if t['passes'] else 'not passing yet'}; evidence `{data['paths']['evidence']}/{t['name']}/`"
                  f"{state(data, 'task:' + t['name'])}" for t in data["tasks"]]
    return "\n".join(lines) + "\n<!-- /hve:checklist -->\n"


def refresh(folder: Path, data: Json) -> list[Json]:
    """Apply ticks the user changed in plan.md since the last render, rewrite the skills and checklist blocks, and return the applied ticks."""
    plan = folder / "plan.md"
    text = plan.read_text(encoding="utf-8") if plan.is_file() else ""
    found = CHECKLIST_BLOCK.search(text)
    applied = []
    for mark, item in TICK.findall(found.group(0)) if found else []:
        now_ticked = mark != " "
        if item in items(data) and now_ticked != data["checklist_rendered"].get(item, False):
            kind = item.split(":", 1)[0]
            value = ("on" if now_ticked else "off") if kind in ("opt", "gate") else ("accepted" if now_ticked else "changes")
            applied.append(record(data, item, value, "", "plan.md"))
    data["pack_load"] = ask_packs.load(data)
    for pattern, block in ((SKILLS_BLOCK, skills_block(data)), (CHECKLIST_BLOCK, checklist_block(data))):
        text = pattern.sub(lambda _: block, text) if pattern.search(text) else (text.rstrip() + "\n\n" if text.strip() else "") + block
    data["checklist_rendered"] = {i: ticked(data, i) for i in items(data)}
    plan.write_text(text, encoding="utf-8")
    return applied
