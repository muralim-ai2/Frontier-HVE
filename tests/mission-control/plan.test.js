'use strict';
/** Verify the formatted plan view: Markdown rendering, its safety, the plan states, and Edit opening plan.md beside Mission Control. */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { workspace, removeWorkspace, json } = require('./helpers');
const { mission } = require('./vscode-stub');
const { ASK, project } = require('./fixtures');
const { snapshot, planDigest } = require('../../extension/ui/workspace-state');
const { render } = require('../../extension/ui/media/markdown');
const { h, text, mount } = require('../../extension/ui/media/vnode');

/** Return every tag in a view tree.
 * @param {import('../../extension/ui/types').VNode | string} node
 * @returns {string[]}
 */
function tags(node) { return typeof node === 'string' ? [] : [node.tag, ...node.children.flatMap(tags)]; }

const GENERATED = '<!-- hve:skills -->\n## Skills and tools (generated by lifecycle.py)\n\n| Skill | Tokens |\n|---|---|\n| ux-flows | 382 |\n<!-- /hve:skills -->\n\n'
  + '<!-- hve:checklist -->\n## Sign-off checklist\n\n- [ ] stage:deliver — Deliver\n<!-- /hve:checklist -->\n';

test('plans render as headings, paragraphs, nested lists, task boxes, tables, quotes and code', () => {
  const blocks = render('# Pawstagram plan\n\nBuild **three** screens with `index.html` and [placedog](https://placedog.net).\n\n'
    + '- Home feed\n  - stories tray\n- [x] Profile\n- [ ] Pack hive\n\n1. Build\n2. Verify\n\n> Keep it shippable.\n\n'
    + '| Screen | Checks |\n|---|---|\n| Home | 3 |\n\n```\nnpm test\n```\n---\n');
  assert.deepEqual(blocks.map(block => block.tag), ['h2', 'p', 'ul', 'ol', 'blockquote', 'div', 'pre', 'hr']);
  const paragraph = blocks[1];
  assert.deepEqual(tags(paragraph), ['p', 'strong', 'code', 'span']);
  assert.equal(paragraph.children[5].attrs.title, 'https://placedog.net');
  assert.ok(tags(blocks[2]).filter(tag => tag === 'ul').length === 2, 'nested list');
  const boxes = blocks[2].children.slice(1).map(item => item.children[0].attrs.class);
  assert.deepEqual(boxes, ['md-box done', 'md-box']);
  assert.equal(text(blocks[5]), 'ScreenChecksHome3');
  assert.equal(text(blocks[6]), 'npm test');
  assert.deepEqual(tags(render('snake_case_name and 2*3*4 stay plain')[0]), ['p']);
});

test('HTML in a plan stays text, comments are dropped, and only allowlisted tags and attributes exist', () => {
  const blocks = render('<script>alert(1)</script>\n\n<img src=x onerror=alert(1)>\n\n<!-- hidden -->Visible');
  assert.deepEqual(blocks.flatMap(tags), ['p', 'p', 'p']);
  assert.equal(text(blocks[0]), '<script>alert(1)</script>');
  assert.equal(text(blocks[2]), 'Visible');
  assert.throws(() => h('script', null), /tag not allowed/);
  assert.throws(() => h('div', { onclick: 'x' }), /attribute not allowed/);
  assert.throws(() => h('div', { href: 'javascript:x' }), /attribute not allowed/);
  /** @type {string[]} */
  const created = [];
  const doc = { createTextNode: value => ({ kind: 'text', value, appendChild() {} }),
    createElement: tag => { created.push(tag); return { attrs: {}, children: [], style: {}, setAttribute(name, value) { this.attrs[name] = value; }, appendChild(child) { this.children.push(child); } }; } };
  const element = mount(h('p', { class: 'x' }, '<b>bold</b>'), /** @type {any} */ (doc));
  assert.deepEqual(created, ['p']);
  assert.deepEqual(element.children[0], { kind: 'text', value: '<b>bold</b>', appendChild: element.children[0].appendChild });
});

test('the plan model separates the written plan from its generated sections and reports where it stands', t => {
  const root = workspace();
  t.after(() => removeWorkspace(root));
  const folder = project(root);
  const planFile = path.join(root, folder, 'plan.md');
  const contractFile = path.join(root, folder, 'contract.json');
  const contract = JSON.parse(fs.readFileSync(contractFile, 'utf8'));
  const write = (plan, sha256, revisions = []) => {
    fs.writeFileSync(planFile, plan);
    json(root, path.join(folder, 'contract.json'), { ...contract, plan: { sha256, revisions } });
    return snapshot(root).plan;
  };
  assert.equal(write(GENERATED, null).status, 'empty');
  const body = '# Workspace policy\n\nReject invalid configuration.';
  const draft = write(`${body}\n\n${GENERATED}`, null);
  assert.equal(draft.status, 'draft');
  assert.equal(draft.body, body);
  assert.match(draft.skills, /^## Skills and tools/);
  assert.ok(!draft.body.includes('hve:checklist'));
  const agreed = write(`${body}\n\n${GENERATED}`, planDigest(body), [{ ts: '2026-10-28T20:30:00+00:00', sha256: planDigest(body), note: 'approved' }]);
  assert.deepEqual({ status: agreed.status, revisions: agreed.revisions, agreedAt: agreed.agreedAt, path: agreed.path },
    { status: 'agreed', revisions: 1, agreedAt: '2026-10-28T20:30:00+00:00', path: `.hve/asks/${ASK}/plan.md` });
  assert.equal(write(`${body}\nAlso support dark mode.\n\n${GENERATED}`, planDigest(body)).status, 'edited');
});

test('Edit plan opens plan.md as a text editor beside Mission Control, and explains when there is none', async t => {
  const fixture = mission(t);
  await assert.rejects(fixture.controls.commands.get('frontierHve.editPlan')(), /no plan\.md/);
  project(fixture.root);
  await fixture.controls.commands.get('frontierHve.editPlan')();
  const opened = fixture.controls.calls.find(call => call[0] === 'document');
  assert.equal(opened[1].fsPath, path.join(fs.realpathSync(fixture.root), '.hve', 'asks', ASK, 'plan.md'));
  assert.deepEqual(opened[2], { viewColumn: -2, preview: false });
});
